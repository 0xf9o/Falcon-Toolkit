// RenderBanner is an alias for Banner.
func RenderBanner(s *Styler) string {
	return Banner(s)
}

// StartupMessage returns the text shown after the banner.
func StartupMessage(s *Styler, workspace string) string {
	msg := "\nType \"help\" for commands.\n"
	if s != nil && s.IsColorEnabled() {
		return s.Muted(msg)
	}
	return msg
}
